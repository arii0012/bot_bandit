void FontUI::BuildPixelFont() {
  const int gw = 8, gh = 8, pad = 1;
  const int cell = gw + pad;
  const int cols = 32;
  const int rows = (kGlyphCount + cols - 1) / cols;
  const int aw = cols * cell + pad;
  const int ah = rows * cell + pad;

  Image img = GenImageColor(aw, ah, {0, 0, 0, 0});

  font_.glyphs = (GlyphInfo*)MemAlloc(kGlyphCount * sizeof(GlyphInfo));
  font_.recs = (Rectangle*)MemAlloc(kGlyphCount * sizeof(Rectangle));
  font_.glyphCount = kGlyphCount;
  font_.glyphPadding = pad;
  font_.baseSize = gh;

  for (int i = 0; i < kGlyphCount; ++i) {
    int col = i % cols;
    int row = i / cols;
    int ox = pad + col * cell;
    int oy = pad + row * cell;
    const auto& g = kGlyphs[i];
    for (int y = 0; y < gh; ++y) {
      unsigned char bits = g.rows[y];
      for (int x = 0; x < gw; ++x) {
        if (bits & (1 << (7 - x)))
          ImageDrawPixel(&img, ox + x, oy + y, WHITE);
      }
    }
    font_.glyphs[i].value = g.cp;
    font_.glyphs[i].offsetX = 0;
    font_.glyphs[i].offsetY = 0;
    font_.glyphs[i].advanceX = gw + 1;
    font_.glyphs[i].image = {0};
    font_.recs[i] = {(float)ox, (float)oy, (float)gw, (float)gh};
  }

  font_.texture = LoadTextureFromImage(img);
  SetTextureFilter(font_.texture, TEXTURE_FILTER_POINT);
  UnloadImage(img);
  owned_ = true;
  ready_ = font_.texture.id != 0;
}

void FontUI::Init() {
  if (ready_) return;
  BuildPixelFont();
}

void FontUI::Shutdown() {
  if (owned_ && font_.texture.id != 0) {
    UnloadTexture(font_.texture);
    if (font_.glyphs) MemFree(font_.glyphs);
    if (font_.recs) MemFree(font_.recs);
    font_.glyphs = nullptr;
    font_.recs = nullptr;
    font_.texture = {};
  }
  owned_ = false;
  ready_ = false;
}

void FontUI::Draw(const char* text, float x, float y, float size, Color color) {
  if (!text) return;
  if (!ready_) Init();
  float spacing = size / 8.f;
  DrawTextEx(font_, text, {x, y}, size, spacing, color);
}

void FontUI::Draw(const std::string& text, float x, float y, float size, Color color) {
  Draw(text.c_str(), x, y, size, color);
}

void FontUI::DrawCentered(const char* text, float cx, float y, float size, Color color) {
  int w = Measure(text, size);
  Draw(text, cx - w * 0.5f, y, size, color);
}

void FontUI::DrawCentered(const std::string& text, float cx, float y, float size, Color color) {
  DrawCentered(text.c_str(), cx, y, size, color);
}

void FontUI::DrawShadow(const char* text, float x, float y, float size, Color color, Color shadow) {
  float o = size / 10.f;
  if (o < 1.f) o = 1.f;
  Draw(text, x + o, y + o, size, shadow);
  Draw(text, x, y, size, color);
}

void FontUI::DrawNeon(const char* text, float x, float y, float size, Color color, Color glow) {
  float o = size / 12.f;
  if (o < 1.f) o = 1.f;
  Color g1 = glow; g1.a = (unsigned char)(glow.a / 3);
  Draw(text, x - o, y, size, g1);
  Draw(text, x + o, y, size, g1);
  Draw(text, x, y - o, size, g1);
  Draw(text, x, y + o, size, g1);
  Draw(text, x, y, size, color);
}

int FontUI::Measure(const char* text, float size) {
  if (!text) return 0;
  if (!ready_) Init();
  float spacing = size / 8.f;
  return (int)MeasureTextEx(font_, text, size, spacing).x;
}

int FontUI::Measure(const std::string& text, float size) {
  return Measure(text.c_str(), size);
}
